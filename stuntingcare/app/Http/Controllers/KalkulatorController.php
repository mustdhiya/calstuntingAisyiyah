    private function getIdealTB(string $gender, int $usia): array
    {
        $lms = $this->getLmsTBU($gender, $usia);
        return [
            'median'  => round($lms['M'], 1),
            'min_normal' => round($lms['M'] + (-2 * $lms['S'] * $lms['M']), 1),
        ];
    }

    private function getIdealBB(string $gender, int $usia): array
    {
        $lms = $this->getLmsBBU($gender, $usia);
        return [
            'median'  => round($lms['M'], 1),
            'min_normal' => round($lms['M'] + (-2 * $lms['S'] * $lms['M']), 1),
        ];
    }

    // =========================================================================
    // WHO 2006 Growth Standards LMS Tables (Height/Length for Age)
    // Source: WHO Multicentre Growth Reference Study Group, 2006
    // =========================================================================

    private function getLmsTBU(string $g, int $usia): array
    {
        $table = ($g === 'L') ? $this->lmsTBU_L() : $this->lmsTBU_P();
        $usia  = max(0, min(60, $usia));
        return $table[$usia] ?? $table[array_key_last($table)];
    }

    private function getLmsBBU(string $g, int $usia): array
    {
        $table = ($g === 'L') ? $this->lmsBBU_L() : $this->lmsBBU_P();
        $usia  = max(0, min(60, $usia));
        return $table[$usia] ?? $table[array_key_last($table)];
    }

    private function getLmsBBTB(string $g, float $tb): array
    {
        // Snap to nearest 0.5 cm then lookup
        $tbKey = round($tb * 2) / 2;
        $table = ($g === 'L') ? $this->lmsBBTB_L() : $this->lmsBBTB_P();
        if (isset($table[(string)$tbKey])) return $table[(string)$tbKey];
        // fallback: get closest
        $keys = array_keys($table);
        $closest = $keys[0];
        foreach ($keys as $k) {
            if (abs($k - $tbKey) < abs($closest - $tbKey)) $closest = $k;
        }
        return $table[$closest];
    }

