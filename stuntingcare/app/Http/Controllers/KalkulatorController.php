    /**
     * Process the calculator form and show results.
     */
    public function hitung(Request $request)
    {
        $data = $request->validate([
            'nama_anak'     => 'nullable|string|max:100',
            'jenis_kelamin' => 'required|in:L,P',
            'usia_bulan'    => 'required|integer|min:0|max:60',
            'tanggal_lahir' => 'nullable|date',
            'tinggi_badan'  => 'required|numeric|min:40|max:130',
            'berat_badan'   => 'required|numeric|min:1|max:50',
            // Optional maternal data
            'tb_ibu'        => 'nullable|numeric|min:100|max:200',
            'bb_ibu'        => 'nullable|numeric|min:30|max:150',
            'asi_eksklusif' => 'nullable|in:ya,tidak',
            'bpjs'          => 'nullable|in:ya,tidak',
        ]);

        $gender = $data['jenis_kelamin'];   // L or P
        $usia   = (int) $data['usia_bulan'];
        $tb     = (float) $data['tinggi_badan'];
        $bb     = (float) $data['berat_badan'];

        // ---------- Z-score calculations ----------
        $zscore_tbu  = $this->calcZscoreTBU($gender, $usia, $tb);
        $zscore_bbu  = $this->calcZscoreBBU($gender, $usia, $bb);
        $zscore_bbtb = $this->calcZscoreBBTB($gender, $tb, $bb);

        // ---------- TB/U classification (stunting indicator) ----------
        $status_tbu = $this->classifyTBU($zscore_tbu);

        // ---------- BB/U classification ----------
        $status_bbu = $this->classifyBBU($zscore_bbu);

        // ---------- BB/TB classification (wasting indicator) ----------
        $status_bbtb = $this->classifyBBTB($zscore_bbtb);

        // ---------- Risk score (0-100) ----------
        $risk_score = $this->calcRiskScore($zscore_tbu, $zscore_bbu, $data);

        // ---------- Risk level ----------
        $risk_level = $this->classifyRisk($risk_score);

        // ---------- Recommendations ----------
        $recommendations = $this->getRecommendations($status_tbu, $status_bbu, $status_bbtb, $usia, $gender, $data);

        // ---------- Ideal ranges for display ----------
        $ideal_tb = $this->getIdealTB($gender, $usia);
        $ideal_bb = $this->getIdealBB($gender, $usia);

        // ---------- Tentukan status_growth untuk disimpan ke DB ----------
        // Mapping dari code TB/U ke label yang disimpan
        $statusGrowthMap = [
            'normal'        => 'Normal',
            'stunting'      => 'Pendek',
            'stunting_berat'=> 'Sangat Pendek',
        ];
        $statusGrowth = $statusGrowthMap[$status_tbu['code']] ?? 'Normal';

        // ---------- Simpan ke tabel measurements ----------
        Measurement::create([
            'child_name'    => $data['nama_anak'] ?? 'Anak',
            'gender'        => $gender,
            'age_months'    => $usia,
            'birth_date'    => $data['tanggal_lahir'] ?? null,
            'height'        => $tb,
            'weight'        => $bb,
            'status_growth' => $statusGrowth,
            'city'          => $request->input('kota') ?? null,
            'asi_eksklusif' => ($request->input('asi_eksklusif') === 'tidak') ? 'Tidak' : 'Ya',
        ]);

        $result = [
            'nama_anak'    => $data['nama_anak'] ?? 'Anak',
            'gender'       => $gender,
            'usia'         => $usia,
            'tb'           => $tb,
            'bb'           => $bb,

            'zscore_tbu'   => round($zscore_tbu, 2),
            'zscore_bbu'   => round($zscore_bbu, 2),
            'zscore_bbtb'  => round($zscore_bbtb, 2),

            'status_tbu'   => $status_tbu,
            'status_bbu'   => $status_bbu,
            'status_bbtb'  => $status_bbtb,

            'risk_score'   => round($risk_score),
            'risk_level'   => $risk_level,

            'ideal_tb'     => $ideal_tb,
            'ideal_bb'     => $ideal_bb,

            'recommendations' => $recommendations,

            // Extra
            'asi_eksklusif' => $data['asi_eksklusif'] ?? null,
            'tb_ibu'        => $data['tb_ibu'] ?? null,
        ];

        return view('public.hasil-kalkulator', compact('result'));
    }

    // =========================================================================
    // WHO Z-score: Height/Length-for-Age (TB/U)
    // Uses LMS method reference from WHO 2006 Growth Standards
    // =========================================================================
    private function calcZscoreTBU(string $gender, int $usia, float $tb): float
    {
        $lms = $this->getLmsTBU($gender, $usia);
        return $this->calcZscore($tb, $lms['L'], $lms['M'], $lms['S']);
    }

    private function calcZscoreBBU(string $gender, int $usia, float $bb): float
    {
        $lms = $this->getLmsBBU($gender, $usia);
        return $this->calcZscore($bb, $lms['L'], $lms['M'], $lms['S']);
    }

    private function calcZscoreBBTB(string $gender, float $tb, float $bb): float
    {
        // Use approximate TB rounded to nearest 0.5
        $lms = $this->getLmsBBTB($gender, $tb);
        return $this->calcZscore($bb, $lms['L'], $lms['M'], $lms['S']);
    }

    /**
     * WHO LMS Z-score formula
     */
    private function calcZscore(float $x, float $L, float $M, float $S): float
    {
        if ($L == 0) {
            return log($x / $M) / $S;
        }
        return (pow($x / $M, $L) - 1) / ($L * $S);
    }

    // =========================================================================
    // Classifications
    // =========================================================================
    private function classifyTBU(float $z): array
    {
        if ($z >= -2) {
            return ['label' => 'Normal', 'color' => 'green', 'badge' => 'badge-success', 'code' => 'normal'];
        } elseif ($z >= -3) {
            return ['label' => 'Pendek (Stunting)', 'color' => 'orange', 'badge' => 'badge-warning', 'code' => 'stunting'];
        } else {
            return ['label' => 'Sangat Pendek (Stunting Berat)', 'color' => 'red', 'badge' => 'badge-error', 'code' => 'stunting_berat'];
        }
    }

    private function classifyBBU(float $z): array
    {
        if ($z >= 2) {
            return ['label' => 'Berat Lebih', 'color' => 'yellow', 'badge' => 'badge-warning', 'code' => 'lebih'];
        } elseif ($z >= -2) {
            return ['label' => 'Normal', 'color' => 'green', 'badge' => 'badge-success', 'code' => 'normal'];
        } elseif ($z >= -3) {
            return ['label' => 'Berat Kurang', 'color' => 'orange', 'badge' => 'badge-warning', 'code' => 'kurang'];
        } else {
            return ['label' => 'Berat Sangat Kurang', 'color' => 'red', 'badge' => 'badge-error', 'code' => 'sangat_kurang'];
        }
    }

    private function classifyBBTB(float $z): array
    {
        if ($z >= 2) {
            return ['label' => 'Gemuk', 'color' => 'yellow', 'badge' => 'badge-warning', 'code' => 'gemuk'];
        } elseif ($z >= -2) {
            return ['label' => 'Normal', 'color' => 'green', 'badge' => 'badge-success', 'code' => 'normal'];
        } elseif ($z >= -3) {
            return ['label' => 'Kurus (Wasting)', 'color' => 'orange', 'badge' => 'badge-warning', 'code' => 'wasting'];
        } else {
            return ['label' => 'Sangat Kurus (Wasting Berat)', 'color' => 'red', 'badge' => 'badge-error', 'code' => 'wasting_berat'];
        }
    }

    private function calcRiskScore(float $zscore_tbu, float $zscore_bbu, array $data): float
    {
        // Z-score TB/U is primary indicator (weight 60%)
        $tbu_score = $this->zscoreToRisk($zscore_tbu) * 0.60;

        // Z-score BB/U secondary (weight 25%)
        $bbu_score = $this->zscoreToRisk($zscore_bbu) * 0.25;

        // Additional risk factors (weight 15%)
        $extra = 0;
        $asi   = $data['asi_eksklusif'] ?? null;
        if ($asi === 'tidak') $extra += 5;

        $tb_ibu = isset($data['tb_ibu']) ? (float) $data['tb_ibu'] : null;
        if ($tb_ibu && $tb_ibu < 150) $extra += 5;

        $bpjs = $data['bpjs'] ?? null;
        if ($bpjs === 'tidak') $extra += 5;

        return min(100, $tbu_score + $bbu_score + $extra);
    }

    private function zscoreToRisk(float $z): float
    {
        // Map Z-score to 0–100 risk range (lower Z = higher risk)
        // Normal ≥ -2, Risk -3 to -2, High < -3
        if ($z >= -1)  return max(0, 30 - ($z * 10));
        if ($z >= -2)  return 30 + ((-1 - $z) * 20);
        if ($z >= -3)  return 50 + ((-2 - $z) * 30);
        return min(100, 80 + ((-3 - $z) * 10));
    }

    private function classifyRisk(float $score): array
    {
        if ($score < 30) {
            return ['label' => 'Risiko Rendah', 'color' => 'green', 'badge' => 'badge-success', 'code' => 'rendah', 'progress' => 'progress-success'];
        } elseif ($score < 60) {
            return ['label' => 'Risiko Sedang', 'color' => 'yellow', 'badge' => 'badge-warning', 'code' => 'sedang', 'progress' => 'progress-warning'];
        } elseif ($score < 80) {
            return ['label' => 'Risiko Tinggi', 'color' => 'orange', 'badge' => 'badge-error', 'code' => 'tinggi', 'progress' => 'progress-error'];
        } else {
            return ['label' => 'Risiko Sangat Tinggi', 'color' => 'red', 'badge' => 'badge-error', 'code' => 'sangat_tinggi', 'progress' => 'progress-error'];
        }
    }

